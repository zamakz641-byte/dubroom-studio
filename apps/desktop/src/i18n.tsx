const catalogs: Record<Locale, Record<string, string>> = {
  fr,
  en,
  es,
  pt,
  de,
  ja,
  ko,
  zh,
  ar,
};
type I18nValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
  number: (value: number) => string;
  date: (value: string | Date, options?: Intl.DateTimeFormatOptions) => string;
};
const Context = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    const saved = localStorage.getItem("dubroom.locale");
    return languages.some((item) => item.id === saved)
      ? (saved as Locale)
      : "fr";
  });
  const setLocale = (next: Locale) => {
    localStorage.setItem("dubroom.locale", next);
    setLocaleState(next);
  };
  useEffect(() => {
    const meta = languages.find((item) => item.id === locale)!;
    document.documentElement.lang = locale;
    document.documentElement.dir = meta.dir;
  }, [locale]);
  const value = useMemo<I18nValue>(
    () => ({
      locale,
      setLocale,
      t: (key, vars) => {
        let value = catalogs[locale][key] ?? en[key] ?? key;
        for (const [name, replacement] of Object.entries(vars || {}))
          value = value.replaceAll(`{{${name}}}`, String(replacement));
        return value;
      },
      number: (value) => new Intl.NumberFormat(locale).format(value),
      date: (value, options) =>
        new Intl.DateTimeFormat(locale, options).format(new Date(value)),
    }),
    [locale],
  );
  return <Context.Provider value={value}>{children}</Context.Provider>;
}

export function useI18n() {
  const value = useContext(Context);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}
